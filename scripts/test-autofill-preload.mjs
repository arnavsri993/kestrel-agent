import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { _electron as electron } from '@playwright/test';
const root = mkdtempSync(join(tmpdir(), 'kestrel-autofill-preload-'));
const preload = resolve('apps/desktop/out/preload/userBrowser.cjs');
const main = join(root, 'main.cjs');
writeFileSync(main, `const {app,BrowserWindow,session,ipcMain}=require('electron');
app.setPath('userData', ${JSON.stringify(join(root,'profile'))});
app.whenReady().then(async()=>{
 await session.defaultSession.protocol.handle('https',()=>new Response('<!doctype html><title>Autofill fixture</title><body></body>',{headers:{'content-type':'text/html'}}));
 globalThis.messages=[];
 for(const channel of ['kestrel:user-browser-password-submission','kestrel:user-browser-profile-submission']) ipcMain.on(channel,(_e,data)=>globalThis.messages.push({channel,data}));
 const win=new BrowserWindow({show:false,width:900,height:600,webPreferences:{preload:${JSON.stringify(preload)},sandbox:true,contextIsolation:true,nodeIntegration:false}});
 await win.loadURL('https://autofill.example.test/');
});`);
let app;
try {
 app = await electron.launch({ executablePath:createRequire(resolve('apps/desktop/package.json'))('electron'), args:[main], env:{...process.env,ELECTRON_RUN_AS_NODE:''} });
 const page = await app.firstWindow();
 await page.waitForURL('https://autofill.example.test/');
 const command = (input) => app.evaluate(async ({BrowserWindow,ipcMain}, input) => {
  const webContents = BrowserWindow.getAllWindows()[0].webContents;
  const requestId = input.requestId;
  return await new Promise((resolve,reject)=>{
   const timer=setTimeout(()=>{ipcMain.removeListener('kestrel:user-browser-credential-response',listener);reject(new Error('Autofill response timed out'));},3000);
   const listener=(_event,result)=>{if(result.requestId!==requestId)return;clearTimeout(timer);ipcMain.removeListener('kestrel:user-browser-credential-response',listener);resolve(result);};
   ipcMain.on('kestrel:user-browser-credential-response',listener);
   webContents.send('kestrel:user-browser-credential-command',{requestId,expectedOrigin:'https://autofill.example.test',...input});
  });
 },{...input,requestId:`password-request-${randomUUID()}`});
 await page.evaluate((html) => { document.body.innerHTML = html; }, `<form><input id="username" autocomplete="section-login username"><input id="password" type="password" autocomplete="section-login current-password"><button type="button" onclick="this.form.remove()">Sign in</button></form>`);
 let scan=await command({type:'scan'});
 assert.deepEqual(scan.snapshot.fields.map(f=>f.kind),['username','password']);
 await command({type:'fill',username:'fixture-user',password:'fixture-secret',onlyEmpty:true});
 assert.equal(await page.locator('#password').inputValue(),'fixture-secret');
 await page.locator('#username').fill('edited-user');
 await command({type:'fill',username:'must-not-overwrite',password:'must-not-overwrite',onlyEmpty:true});
 assert.equal(await page.locator('#username').inputValue(),'edited-user');
 assert.equal(await page.locator('#password').inputValue(),'fixture-secret');
 await page.getByRole('button',{name:'Sign in'}).click();
 assert.equal(await app.evaluate(()=>globalThis.messages.some(m=>m.channel.endsWith('password-submission') && m.data.username==='edited-user' && m.data.password==='fixture-secret')),true);
 await page.evaluate((html) => { document.body.innerHTML = html; }, `<form onsubmit="event.preventDefault()"><input id="first" autocomplete="section-shipping given-name"><input id="street" autocomplete="shipping address-line1"><input id="birthday" type="date" autocomplete="bday"><select id="country" autocomplete="country"><option value="">Choose</option><option value="US">United States</option></select><input id="readonly" autocomplete="family-name" readonly><input id="hidden" autocomplete="email" style="display:none"><input id="otp" autocomplete="one-time-code"><div style="height:900px"></div><input id="city" autocomplete="address-level2"><button>Save details</button></form>`);
 await page.locator('#first').focus();
 scan=await command({type:'scan'});
 assert.equal(scan.snapshot.fields.some(f=>f.label==='readonly'),false);
 const firstId=scan.snapshot.fields.find(f=>f.autocomplete==='given-name').id;
 await command({type:'fill',profile:{'given-name':'Fixture','address-line1':'12 Test Lane','bday':'2000-02-03','country':'US','family-name':'Do not fill','email':'fixture@example.test','address-level2':'Example City'},onlyEmpty:true});
 assert.equal(await page.locator('#first').inputValue(),'Fixture');
 assert.equal(await page.locator('#country').inputValue(),'US');
 assert.equal(await page.locator('#birthday').inputValue(),'2000-02-03');
 assert.equal(await page.locator('#city').inputValue(),'Example City');
 assert.equal(await page.locator('#hidden').inputValue(),'');
 assert.equal(await page.locator('#readonly').inputValue(),'');
 assert.equal(await page.locator('#otp').inputValue(),'');
 await page.evaluate(()=>document.querySelector('#first').insertAdjacentHTML('beforebegin','<input autocomplete="name">'));
 await command({type:'fill',fieldId:firstId,profile:{'given-name':'Stable target'}});
 assert.equal(await page.locator('#first').inputValue(),'Stable target');
 await page.locator('#first').fill('Learned name');
 await page.getByRole('button',{name:'Save details'}).click();
 assert.equal(await app.evaluate(()=>globalThis.messages.some(m=>m.channel.endsWith('profile-submission') && m.data['given-name']==='Learned name' && !m.data['address-line1'])),true);
 await page.evaluate((html) => { document.body.innerHTML = html; }, '<input id="new" type="password" autocomplete="new-password">');
 await command({type:'fill',username:'fixture',password:'existing-secret'});
 assert.equal(await page.locator('#new').inputValue(),'');
 scan=await command({type:'scan'});
 await command({type:'fill',fieldId:scan.snapshot.fields[0].id,password:'generated-fixture'});
 assert.equal(await page.locator('#new').inputValue(),'generated-fixture');
 console.log('PASS: real isolated preload login, SPA capture, profile fill, offscreen fields, select/date, stable IDs, typed-value preservation, capture allowlist, and signup separation.');
} finally { if(app) await app.close(); rmSync(root,{recursive:true,force:true}); }
