import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { _electron as electron, expect } from '@playwright/test';
const root = mkdtempSync(join(tmpdir(), 'kestrel-agent-composer-'));
const evidence = resolve('.tmp/agent-composer');
mkdirSync(evidence, { recursive: true });
let app;
try {
 app = await electron.launch({ executablePath: resolve(process.env.KESTREL_DESKTOP_EXECUTABLE ?? 'release/mac-arm64/Kestrel.app/Contents/MacOS/Kestrel'), args: ['--use-mock-keychain'], env: { ...process.env, KESTREL_TEST_USER_DATA: join(root,'profile'), KESTREL_TEST_ALLOW_MULTIPLE_INSTANCES:'1', KESTREL_DISABLE_UPDATES:'1', KESTREL_DISABLE_SUBSCRIPTION_CLI_DISCOVERY:'1', KESTREL_DISABLE_LOCAL_MODEL_DISCOVERY:'1' } });
 const page = await app.firstWindow();
 await page.evaluate(() => { localStorage.setItem('kestrel:onboarded','yes'); localStorage.setItem('kestrel:default-browser-prompted','yes'); });
 await page.reload();
 await page.locator('.kestrel-sidebar').getByRole('button',{name:'Agent',exact:true}).click();
 await page.getByRole('button',{name:'Create an agent',exact:true}).click();
 await page.getByLabel('Agent template',{exact:true}).selectOption('robotics');
 await page.getByRole('button',{name:'Create agent',exact:true}).click();
 await page.getByRole('searchbox',{name:'Find a system or task'}).fill('Robotics');
 await page.getByRole('searchbox',{name:'Find a system or task'}).press('Enter');
 await page.locator('.agent-universe-node.is-core').first().click();
 const composer = page.locator('.agent-universe-context-composer');
 const input = composer.locator('textarea');
 await input.waitFor();
 const resting = await composer.boundingBox();
 await input.focus();
 await expect(composer).toHaveClass(/is-expanded/);
 await expect.poll(async () => (await composer.boundingBox()).height).toBeGreaterThan(resting.height + 20);
 assert.equal(await input.evaluate(el=>getComputedStyle(el).fontSize),'14px');
 await composer.locator('.model-selector-trigger').click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(composer.locator('.model-selector-trigger')).toBeFocused();
 await input.fill('Robotics draft');
 await input.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true,bubbles:true,cancelable:true});
 assert.equal(await input.inputValue(),'Robotics draft');
 await input.press('Shift+Enter');
 assert.match(await input.inputValue(), /\n/);
 assert.equal(await input.evaluate(el => getComputedStyle(el).outlineStyle), 'none');
 await page.screenshot({path:join(evidence,'composer.png')});
 await app.evaluate(({BrowserWindow})=>{const win=BrowserWindow.getAllWindows()[0]; win.setMinimumSize(400,500); win.setSize(1200,900); win.webContents.setZoomFactor(2);});
 await page.waitForFunction(() => Math.abs(innerWidth - 600) < 3);
 await input.scrollIntoViewIfNeeded();
 await expect(input).toBeVisible();
 await expect(composer.getByRole('button',{name:'Send message to Robotics'})).toBeVisible();
 const bounds = await composer.boundingBox();
 assert(bounds.x >= 0 && bounds.x + bounds.width <= await page.evaluate(()=>innerWidth) + 1);
 assert(bounds.y >= 0 && bounds.y + bounds.height <= await page.evaluate(()=>innerHeight) + 1);
 const zoomImage = await app.evaluate(async ({BrowserWindow}) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'));
 writeFileSync(join(evidence,'composer-zoom.png'), Buffer.from(zoomImage,'base64'));
 console.log('Agent composer passed: shared surface, focus expansion, real model picker, IME, multiline, 200% zoom.');
} finally { await app?.close(); rmSync(root,{recursive:true,force:true}); }
